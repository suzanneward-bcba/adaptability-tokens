# Start a board, full screen, keep-or-switch, pictures instead of emojis.
import asyncio, sys, re
from playwright.async_api import async_playwright
def ok(c,m):
    if not c: print('✗',m); sys.exit(1)
    print('✓',m)
EMOJI = re.compile('[\U0001F000-\U0001FAFF☀-⛿⭐⬆⬇⏱⏸]')
async def award(pg, lid):
    await pg.evaluate("""id=>{const e=document.createElement('button');e.dataset.a='award';e.dataset.st='learner';e.dataset.id=id;document.body.appendChild(e);e.click();e.remove();}""", lid)
    await pg.wait_for_timeout(700)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(viewport={'width':1180,'height':820})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
        await pg.goto('http://localhost:8765/?demo=1'); await pg.wait_for_selector('.tile')
        ok(not EMOJI.search(await pg.locator('body').inner_text()),'home has no emojis')
        await pg.click('[data-a="startOpen"]')
        for d in '1234': await pg.click(f'.pinpad button[data-v="{d}"]')
        await pg.click('[data-a="startWho"][data-id="l-leo"]')
        await pg.click('[data-a="startSet"][data-f="theme"][data-v="dino"]')
        await pg.click('[data-a="startSet"][data-f="target"][data-v="3"]')
        await pg.click('[data-a="startLibToggle"]'); await pg.click('[data-a="startLib"][data-p="swing"]')
        await pg.fill('#r-l','Big swing'); await pg.click('[data-a="saveR"]'); await pg.wait_for_selector('.startform')
        ok('Big swing' in await pg.locator('.choice[aria-pressed="true"]').inner_text(),'therapist-named library reward is selected')
        await pg.check('[data-start-offer]')
        ok(not EMOJI.search(await pg.locator('body').inner_text()),'start screen has no emojis')
        await pg.click('[data-a="startGo"]'); await pg.wait_for_selector('.lvstage')
        ok(await pg.locator('.bar').count()==0,'full screen: no top bar')
        ok('Big swing' in await pg.locator('.rcorner').inner_text(),'reward shown in the corner')
        box = await pg.locator('.lvstage .themebox').bounding_box()
        ok(box['height']>480,'board fills most of the screen (%d px tall)'%box['height'])
        st = await pg.evaluate("__AT.state.learners.find(x=>x.id==='l-leo')")
        ok(st['theme']=='dino' and st['target']==3 and st['choiceTiming']=='both' and st['board']['earned']==0,'learner saved with dino, 3 tokens, both timing, empty board')
        for i in range(3): await award(pg,'l-leo')
        await pg.wait_for_timeout(3600)
        ok(await pg.locator('.keepbtn').count()==1,'keep-or-switch appears at the finish')
        await pg.click('.modal .choice[data-r="r-lightshow"]'); await pg.wait_for_timeout(200)
        ok(await pg.locator('.modal').count()==0 and 'Light show' in await pg.locator('.rcorner').inner_text(),'switching closes the screen and updates the reward')
        ok(not EMOJI.search(await pg.locator('body').inner_text()),'full-screen board has no emojis')
        await pg.screenshot(path='/home/claude/tokens/shots/40-start-finish.png')
        await pg.evaluate('document.fullscreenElement && document.exitFullscreen()'); await pg.wait_for_timeout(300); await pg.set_viewport_size({'width':820,'height':1180}); await pg.wait_for_timeout(200)
        await pg.screenshot(path='/home/claude/tokens/shots/41-portrait.png')
        ok(await pg.evaluate('document.documentElement.scrollWidth<=innerWidth'),'portrait: no sideways scroll')
        ok(not errs,'no console errors '+str(errs))
        await b.close()
asyncio.run(main())
